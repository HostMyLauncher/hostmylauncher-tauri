//! Registration metadata derived from the same list as the real Tauri handler.
//! Never maintain a second command list.
macro_rules! command_metadata {
    ($($key:ident => $command:ident,)*) => {
        pub const COMMANDS: &[(&str, &str)] = &[
            $((stringify!($key), concat!("plugin:hostmylauncher|", stringify!($command))),)*
        ];
    };
}
crate::hostmylauncher_commands!(command_metadata);
pub const PLUGIN_NAME: &str = "hostmylauncher";
pub const OPERATION_EVENT: &str = "hostmylauncher://operation";

pub fn typescript_contract() -> String {
    let mut output = String::from("// Generated by generate-contract. Do not edit.\n");
    output.push_str(&crate::contract::typescript_types());
    output.push_str("\nexport const COMMANDS = {\n");
    for (key, command) in COMMANDS {
        output.push_str(&format!("  {key}: '{command}',\n"));
    }
    output.push_str("} as const;\n");
    output.push_str(&format!(
        "export const OPERATION_EVENT = '{OPERATION_EVENT}' as const;\n"
    ));
    output
}
